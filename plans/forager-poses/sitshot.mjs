// node plans/forager-poses/sitshot.mjs out.png [port] [zoom] (server running): the forager sat on a seat log by a lit fire, in the game
import { spawn } from 'node:child_process';
import { writeFileSync, mkdtempSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const out = process.argv[2] || 'sit.png', port = process.argv[3] || 8765, zoom = +(process.argv[4] || 90);
const dbg = 9333 + Math.floor(Math.random() * 500);
const prof = mkdtempSync(join(tmpdir(), 'pose-'));
const ch = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--remote-debugging-port=' + dbg, '--user-data-dir=' + prof, '--window-size=900,700', '--force-device-scale-factor=2', '--hide-scrollbars', `http://localhost:${port}/?seed=123&dev`], { stdio: 'ignore' });
const wait = ms => new Promise(r => setTimeout(r, ms));
let tabs; for (let i = 0; i < 50; i++) { try { tabs = await (await fetch(`http://127.0.0.1:${dbg}/json`)).json(); if (tabs.find(t => t.type === 'page')) break; } catch {} await wait(200); }
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0; const pend = {};
ws.onmessage = m => { const d = JSON.parse(m.data); if (pend[d.id]) { pend[d.id](d.result); delete pend[d.id]; } };
const cmd = (method, params = {}) => new Promise(r => { pend[++id] = r; ws.send(JSON.stringify({ id, method, params })); });
const ev = async e => { const r = await cmd('Runtime.evaluate', { expression: e, awaitPromise: true, returnByValue: true }); return r.result && r.result.value !== undefined ? r.result.value : r; };
await wait(6000);
console.log(await ev(`(() => { const S = window.Sim, w = garden.world, f = w.forager;
  const F = S.layFire(w, f.x + 1.6, f.y - 0.5, 3, 1); S.lightFire(w, F);
  const Q = S.makeSeat(w, f.x, f.y - 1.5, 0);
  if (!Q) return 'no seat ' + JSON.stringify(!!w.camp);
  f.x = Q.x; f.y = Q.y + S.SEAT_OUT; f.walking = false;
  garden.cam.goal = null; garden.cam.x = Q.x; garden.cam.y = Q.y; garden.cam.zoom = ${zoom};
  const st = document.createElement('style'); st.textContent = 'body > *:not(#world, #ground) { visibility: hidden }'; document.head.appendChild(st);
  return 'ok ' + Q.x.toFixed(1) + ',' + Q.y.toFixed(1); })()`));
await wait(1500);
await ev(`garden.cam.goal = null; garden.cam.zoom = ${zoom}; garden.cam.x = garden.world.camp.seat.x; garden.cam.y = garden.world.camp.seat.y`);
await wait(1500);
console.log(await ev(`garden.forager.kneel + ' ' + garden.cam.zoom`));
const [sx, sy] = await ev(`garden.screen(garden.world.forager.x, garden.world.forager.y)`);
const k = zoom < 20 ? 0.45 : 1, s = await cmd('Page.captureScreenshot', { format: 'png', clip: { x: sx - 70 * k, y: sy - 110 * k, width: 140 * k, height: 140 * k, scale: 3 / k } });
writeFileSync(out, Buffer.from(s.data, 'base64'));
ch.kill(); process.exit(0);
